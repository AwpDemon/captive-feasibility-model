"""Command-line entry point: ``captive run`` regenerates every deliverable from the YAML config."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import numpy as np

from . import excel, figures, memo
from .analysis import Study
from .config import load_config, with_overrides

ROOT = Path(__file__).resolve().parents[2]
README_START, README_END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def _jsonable(obj):
    if isinstance(obj, dict):
        return {str(k): _jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_jsonable(v) for v in obj]
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    if isinstance(obj, (np.floating, np.integer, np.bool_)):
        return obj.item()
    return obj


def summary_markdown(out: dict, cfg: dict) -> str:
    """The results block pasted into the README (regenerated on every run)."""
    def m(x):
        return f"-${-x:,.0f}" if x < 0 else f"${x:,.0f}"

    rec = out["recommendation"]
    lines = [
        f"**Model decision:** {rec['headline']}",
        "",
        f"_{out['meta']['n_sims']:,} Monte Carlo paths, seed {out['meta']['seed']}, 5 policy years + full run-off, "
        f"discount rate {out['meta']['discount_rate']:.0%}. Hypothetical company; reproduce with `captive run`._",
        "",
        "| Program | Mean PV of 5-yr after-tax cost | 95th pct | Saving vs guaranteed cost | P(cheaper than GC) |",
        "|---|---:|---:|---:|---:|",
    ]
    for p in sorted(out["programs"], key=lambda q: q["mean"]):
        lines.append(f"| {p['label']} | {m(p['mean'])} | {m(p['p95'])} | {m(p['saving_vs_gc_mean'])} | "
                     f"{p['prob_cheaper_than_gc']:.1%} |")
    cap = out["capital"]
    a = cap["annual_retained"]
    be = rec.get("focus_breakeven_vs_gc")
    focus = next(p for p in out["programs"] if p["id"] == cfg["focus_captive"])
    lines += [
        "",
        f"| {focus['label']} ({cfg['domiciles'][cfg['captive']['base_domicile']]['name']}) | Value |",
        "|---|---:|",
        f"| Year-1 retained loss: mean / 1-in-100 / 1-in-200 | {m(a['mean'])} / {m(a['p99_1_in_100'])} / "
        f"{m(a['p995_1_in_200'])} |",
        f"| Capital held (max of statutory minimum, 1-in-100 VaR need, premium/3) | {m(cap['capital'])} |",
        f"| P(surplus dips below statutory minimum in years 1-5) | {cap['prob_surplus_below_min_any_year']:.1%} |",
        f"| 1-in-200 total parent capital call | {m(cap['capital_call_1_in_200'])} |",
        "| Break-even vs guaranteed cost (year-1 GC premium) | "
        + (f"{m(be['gc_premium_yr1'])} (~{be['scale']:.1f}x today's {m(rec['gc_premium_yr1'])})" if be else "not reached")
        + " |",
        "| Break-even vs large deductible | "
        + ("not reached in tested range (up to ~6x)" if not rec.get("focus_breakeven_vs_ld") else
           m(rec["focus_breakeven_vs_ld"]["gc_premium_yr1"])) + " |",
    ]
    if out.get("domiciles"):
        lines += ["", "| Domicile (same captive) | Statutory min capital | Premium tax yr 1 | Mean PV cost |",
                  "|---|---:|---:|---:|"]
        lines += [f"| {d['name']} | {m(d['min_capital'])} | {m(d['premium_tax_yr1'])} | {m(d['pv_cost_mean'])} |"
                  for d in out["domiciles"]]
    lines += ["", f"_Generated by `captive run` in {out['meta']['runtime_seconds']:.0f}s._"]
    return "\n".join(lines)


def update_readme(block: str, readme: Path) -> bool:
    if not readme.exists():
        return False
    text = readme.read_text(encoding="utf-8")
    if README_START not in text:
        return False
    new = re.sub(re.escape(README_START) + r".*?" + re.escape(README_END),
                 lambda _: f"{README_START}\n{block}\n{README_END}", text, flags=re.S)
    readme.write_text(new, encoding="utf-8")
    return True


def cmd_run(args) -> int:
    cfg = load_config(args.config)
    if args.quick:
        cfg = with_overrides(cfg, {"meta.n_sims": 5000, "breakeven.sims": 3000})
    if args.sims:
        cfg = with_overrides(cfg, {"meta.n_sims": args.sims})
    outdir = Path(args.outdir).resolve()
    fig_dir = outdir / "docs" / "figures"
    print(f"Running study: {cfg['meta']['n_sims']:,} simulations, seed {cfg['meta']['seed']}")
    out = Study(cfg, verbose=True).run()

    figs = figures.make_all(out, fig_dir)
    print(f"Figures -> {fig_dir}")
    (outdir / "results").mkdir(parents=True, exist_ok=True)
    slim = {k: v for k, v in out.items() if k not in ("pv_samples", "retained_samples")}
    (outdir / "results" / "results.json").write_text(json.dumps(_jsonable(slim), indent=1), encoding="utf-8")
    block = summary_markdown(out, cfg)
    (outdir / "results" / "summary.md").write_text(block + "\n", encoding="utf-8")
    xlsx = excel.build_workbook(out, cfg, outdir / "deliverables" / "captive_feasibility_model.xlsx", figs)
    print(f"Workbook -> {xlsx}")
    blocks = memo.build_blocks(out, cfg, fig_dir)
    md_path = outdir / "docs" / "feasibility_memo.md"
    md_path.write_text(memo.to_markdown(blocks, img_rel=Path("figures")), encoding="utf-8")
    pdf = memo.to_pdf(blocks, outdir / "deliverables" / "feasibility_memo.pdf")
    print(f"Memo -> {md_path} and {pdf}")
    if not args.no_readme and update_readme(block, outdir / "README.md"):
        print("README results block updated")
    print("\n" + out["recommendation"]["headline"])
    return 0


def cmd_summary(args) -> int:
    path = Path(args.outdir) / "results" / "summary.md"
    if not path.exists():
        print("No results yet - run `captive run` first.", file=sys.stderr)
        return 1
    print(path.read_text(encoding="utf-8"))
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="captive", description="Captive feasibility model (hypothetical company)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    run = sub.add_parser("run", help="run the full study and regenerate all deliverables")
    run.add_argument("--config", default=None, help="path to assumptions YAML (default: config/assumptions.yaml)")
    run.add_argument("--sims", type=int, default=None, help="override number of simulations")
    run.add_argument("--quick", action="store_true", help="5,000 simulations for a fast smoke run")
    run.add_argument("--outdir", default=str(ROOT), help="where to write results/docs/deliverables")
    run.add_argument("--no-readme", action="store_true", help="do not touch README.md")
    run.set_defaults(func=cmd_run)
    s = sub.add_parser("summary", help="print the last run's results table")
    s.add_argument("--outdir", default=str(ROOT))
    s.set_defaults(func=cmd_summary)
    args = ap.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
